import type { jsPDF as JsPdfInstance } from 'jspdf'

type JsPdfCtor = new (options?: { unit?: string; format?: string | number[]; orientation?: string }) => JsPdfInstance

export interface PdfSection {
  heading?: string
  columns: string[]
  rows: (string | number)[][]
  /** Relative column widths, e.g. [3, 1, 1.4] */
  widths?: number[]
}

export interface PdfReportOptions {
  title: string
  subtitle?: string
  shopName: string
  sections: PdfSection[]
  footer?: string
  filename: string
}

/**
 * Lightweight A4 PDF for shop reports. English-only labels because jsPDF core
 * fonts cannot embed Devanagari (the on-screen + Excel versions keep Hindi).
 */
export async function downloadReportPdf({
  title,
  subtitle,
  shopName,
  sections,
  footer,
  filename,
}: PdfReportOptions): Promise<void> {
  const { jsPDF } = await import('jspdf')
  const doc = new jsPDF({ unit: 'mm', format: 'a4' }) as JsPdfInstance
  const pageWidth = 210
  const margin = 14
  const contentWidth = pageWidth - margin * 2
  let y = 18

  const header = () => {
    doc.setFont('helvetica', 'bold')
    doc.setFontSize(15)
    doc.text(shopName, margin, y)
    y += 6
    doc.setFontSize(12)
    doc.text(title, margin, y)
    y += 5
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(9)
    if (subtitle) {
      doc.text(subtitle, margin, y)
      y += 4
    }
    doc.text(`Generated ${new Date().toLocaleString('en-IN')}`, margin, y)
    y += 3
    doc.setDrawColor(200)
    doc.line(margin, y, pageWidth - margin, y)
    y += 6
  }

  header()

  const ensureSpace = (needed: number) => {
    if (y + needed > 285) {
      doc.addPage()
      y = 18
      header()
    }
  }

  for (const section of sections) {
    if (section.heading) {
      ensureSpace(10)
      doc.setFont('helvetica', 'bold')
      doc.setFontSize(10.5)
      doc.text(section.heading, margin, y)
      y += 5
    }
    const widths = section.widths ?? section.columns.map(() => 1)
    const total = widths.reduce((sum, width) => sum + width, 0)
    const columnWidths = widths.map((width) => (width / total) * contentWidth)

    ensureSpace(12)
    doc.setFont('helvetica', 'bold')
    doc.setFontSize(8.5)
    let x = margin
    section.columns.forEach((column, index) => {
      const align = index === 0 ? 'left' : 'right'
      const textX = align === 'left' ? x : x + columnWidths[index] - 1
      doc.text(String(column).toUpperCase(), textX, y, { align })
      x += columnWidths[index]
    })
    y += 2
    doc.setDrawColor(220)
    doc.line(margin, y, pageWidth - margin, y)
    y += 4

    doc.setFont('helvetica', 'normal')
    doc.setFontSize(8.5)
    for (const row of section.rows) {
      ensureSpace(6)
      let cellX = margin
      row.forEach((cell, index) => {
        const align = index === 0 ? 'left' : 'right'
        const value = String(cell)
        const maxWidth = columnWidths[index] - 2
        const lines = doc.splitTextToSize(value, maxWidth) as string[]
        const textX = align === 'left' ? cellX : cellX + columnWidths[index] - 1
        doc.text(lines[0] ?? '', textX, y, { align })
        cellX += columnWidths[index]
      })
      y += 4.4
    }
    if (!section.rows.length) {
      doc.setTextColor(120)
      doc.text('No data for this period', margin, y)
      doc.setTextColor(20)
      y += 4.4
    }
    y += 3
  }

  if (footer) {
    ensureSpace(12)
    doc.setDrawColor(200)
    doc.line(margin, y, pageWidth - margin, y)
    y += 5
    doc.setFontSize(8)
    doc.setTextColor(110)
    doc.text(footer, margin, y)
  }

  doc.setFontSize(7.5)
  doc.setTextColor(140)
  doc.text('Generated by Dukaan Dost', pageWidth - margin, 290, { align: 'right' })

  doc.save(`${filename}.pdf`)
}
