/* Static consistency checks: element ids, asset paths, offline cache list.
 * Run with `npm run check`. */

import { existsSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const read = (file) => readFileSync(join(root, file), "utf8");

let failures = 0;
const fail = (message) => {
  failures += 1;
  console.log(`  FAIL ${message}`);
};
const ok = (message) => console.log(`  ok   ${message}`);

const html = read("index.html");
const app = read("src/app.js");
const css = read("src/styles.css");
const sw = read("sw.js");

console.log("element ids");
const usedIds = new Set([...app.matchAll(/\$\("([\w-]+)"\)/g)].map((m) => m[1]));
const declaredIds = new Set([...html.matchAll(/\sid="([\w-]+)"/g)].map((m) => m[1]));
const missing = [...usedIds].filter((id) => !declaredIds.has(id));
if (missing.length) fail(`ids used in app.js but missing from index.html: ${missing.join(", ")}`);
else ok(`${usedIds.size} ids all exist in the markup`);

const unused = [...declaredIds].filter((id) => !usedIds.has(id) && !["main", "listSheet"].includes(id));
if (unused.length) console.log(`  note unused ids: ${unused.join(", ")}`);

console.log("assets");
const refs = new Set([
  ...[...html.matchAll(/(?:href|src)="([^"#:]+)"/g)].map((m) => m[1]),
]);
for (const ref of refs) {
  if (/^https?:/.test(ref)) continue;
  if (!existsSync(join(root, ref))) fail(`missing file referenced by index.html: ${ref}`);
}
ok(`${refs.size} local references checked`);

console.log("offline cache list");
for (const match of sw.matchAll(/"\.\/([^"]*)"/g)) {
  const path = match[1];
  if (!path) continue;
  if (!existsSync(join(root, path))) fail(`sw.js precaches a missing file: ${path}`);
}
ok("every precached asset exists");

console.log("module graph");
for (const file of ["src/app.js", "src/data.js", "src/i18n.js", "src/map.js", "src/quiz.js", "src/store.js", "src/audio.js"]) {
  const code = read(file);
  for (const match of code.matchAll(/from "\.\/([\w-]+\.js)"/g)) {
    if (!existsSync(join(root, "src", match[1]))) fail(`${file} imports a missing module: ${match[1]}`);
  }
}
ok("imports resolve");

console.log("css");
const jsClasses = new Set([
  ...[...`${html}${app}`.matchAll(/class="([^"]+)"/g)].flatMap((m) => m[1].split(/\s+/)),
  ...[...app.matchAll(/classList\.(?:add|toggle|remove)\("([\w-]+)"/g)].map((m) => m[1]),
  ...[...app.matchAll(/setClass\([^,]+,\s*"([\w-]+)"/g)].map((m) => m[1]),
]);
const cssClasses = new Set([...css.matchAll(/\.([a-zA-Z][\w-]*)/g)].map((m) => m[1]));
const unstyled = [...jsClasses].filter((c) => c && !cssClasses.has(c));
if (unstyled.length) console.log(`  note classes without styles: ${unstyled.join(", ")}`);
ok("stylesheet parsed");

console.log("map data");
const mapJs = read("src/map-data.js");
if (!mapJs.startsWith("/* Generated by tools/build_map.py")) fail("map-data.js is not a generated file");
const map = JSON.parse(mapJs.slice(mapJs.indexOf("=") + 1).replace(/;\s*$/, ""));
ok(`${map.shapes.length} shapes, viewBox ${map.width}x${map.height}`);
const dataIds = new Set([...read("src/data.js").matchAll(/^\s{4}id: "([\w-]+)",/gm)].map((m) => m[1]));
const mapIds = new Set(map.shapes.map((s) => s.id));
for (const id of mapIds) if (!dataIds.has(id)) fail(`shape ${id} has no content entry`);
for (const id of dataIds) if (!mapIds.has(id)) fail(`content entry ${id} has no shape`);
ok(`${mapIds.size} shapes match ${dataIds.size} content entries`);

console.log(failures ? `\n${failures} problem(s)` : "\nstatic checks passed");
process.exit(failures ? 1 : 0);
